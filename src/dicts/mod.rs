//! Dictionary storage and lookup.
//!
//! The dictionaries are compiled by `build.rs` into a zero-copy `rkyv`
//! archive that is embedded in the binary and accessed in place — no parsing
//! or deserialization happens at runtime. All romanization logic goes through
//! the [`Dicts`] facade defined here, so the storage representation stays
//! private to this module.
//!
//! `src/dicts/{strutil,model,parse}.rs` are shared with `build.rs` via
//! `#[path]` modules; `parse.rs` is intentionally *not* compiled into the
//! library (only `build.rs` uses it).

pub(crate) mod model;

use std::sync::LazyLock;

use rkyv::rend::char_le;

pub(crate) use model::AbugidaRuleType;
use model::{ArchivedDictionaries, ArchivedNumProp, ArchivedRomRule};

/// Runtime rule type as seen by the lattice.
pub(crate) type Rule = ArchivedRomRule;

static HANGUL_LEADS: &[&str] = &[
    "g", "gg", "n", "d", "dd", "r", "m", "b", "bb", "s", "ss", "-", "j", "jj", "c", "k", "t", "p",
    "h",
];
static HANGUL_VOWELS: &[&str] = &[
    "a", "ae", "ya", "yae", "eo", "e", "yeo", "ye", "o", "wa", "wai", "oe", "yo", "u", "weo", "we",
    "wi", "yu", "eu", "yi", "i",
];
static HANGUL_TAILS: &[&str] = &[
    "-", "g", "gg", "gs", "n", "nj", "nh", "d", "l", "lg", "lm", "lb", "ls", "lt", "lp", "lh", "m",
    "b", "bs", "s", "ss", "ng", "j", "c", "k", "t", "p", "h",
];

/// The embedded dictionary archive, 16-byte aligned for zero-copy access.
static DICT_BYTES: &[u8] = {
    #[repr(C, align(16))]
    struct Aligned<T: ?Sized>(T);

    static ALIGNED: &Aligned<[u8]> =
        &Aligned(*include_bytes!(concat!(env!("OUT_DIR"), "/dicts.rkyv")));

    &ALIGNED.0
};

static GLOBAL: LazyLock<&'static ArchivedDictionaries> = LazyLock::new(|| {
    // SAFETY: the archive is generated by our own `build.rs` from the bundled
    // data files and embedded verbatim; it is trusted and correctly aligned.
    unsafe { rkyv::access_unchecked::<ArchivedDictionaries>(DICT_BYTES) }
});

/// The raw bytes of the embedded dictionary archive.
///
/// Useful for writing a sidecar dictionary file that can later be loaded with
/// [`crate::Uroman::from_dictionary_file`] (requires the `mmap` feature).
pub fn archive_bytes() -> &'static [u8] {
    DICT_BYTES
}

/// Validates and leaks an external archive buffer (e.g. a memory map),
/// returning a dictionary handle backed by it.
#[cfg(feature = "mmap")]
pub(crate) fn access_external(bytes: &'static [u8]) -> Result<Dicts, rkyv::rancor::Error> {
    let archived = rkyv::access::<ArchivedDictionaries, rkyv::rancor::Error>(bytes)?;
    Ok(Dicts { d: archived })
}

/// Cheap, copyable handle to a dictionary set.
#[derive(Clone, Copy)]
pub(crate) struct Dicts {
    d: &'static ArchivedDictionaries,
}

impl std::fmt::Debug for Dicts {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("Dicts")
    }
}

impl Dicts {
    pub fn global() -> Self {
        Self { d: *GLOBAL }
    }

    /// All rule candidates for a source string, in load order.
    pub fn rom_rules(&self, s: &str) -> &'static [Rule] {
        self.d.rom_rules.get(s).map(|v| v.as_slice()).unwrap_or(&[])
    }

    /// True if `s` is a prefix of some `rom_rules` key.
    pub fn is_s_prefix(&self, s: &str) -> bool {
        self.d.s_prefixes.contains(s)
    }

    /// The script name of a character, or `""` if unknown.
    pub fn chr_script_name(&self, c: char) -> &'static str {
        self.d
            .char_scripts
            .get(&char_le::from_native(c))
            .map(|s| s.as_str())
            .unwrap_or("")
    }

    /// The Unicode name of a character, with data-file overrides.
    pub fn chr_name(&self, c: char) -> String {
        if let Some(name) = self.d.char_names.get(&char_le::from_native(c)) {
            return name.as_str().to_string();
        }
        unicode_names2::name(c)
            .map(|n| n.to_string())
            .unwrap_or_default()
    }

    pub fn is_vowel_sign(&self, c: char) -> bool {
        self.d.vowel_signs.contains(&char_le::from_native(c))
    }

    pub fn is_medial_consonant_sign(&self, c: char) -> bool {
        self.d
            .medial_consonant_signs
            .contains(&char_le::from_native(c))
    }

    pub fn is_virama(&self, c: char) -> bool {
        self.d.viramas.contains(&char_le::from_native(c))
    }

    /// The tone-mark class of a character, or `""`.
    pub fn tone_mark(&self, c: char) -> &'static str {
        self.d
            .tone_marks
            .get(&char_le::from_native(c))
            .map(|s| s.as_str())
            .unwrap_or("")
    }

    /// The syllable placement info of a character, or `""`.
    pub fn syllable_info(&self, c: char) -> &'static str {
        self.d
            .syllable_infos
            .get(&char_le::from_native(c))
            .map(|s| s.as_str())
            .unwrap_or("")
    }

    /// Abugida behavior for a lowercase script name.
    pub fn abugida_script(&self, lc_script_name: &str) -> Option<(AbugidaRuleType, &'static str)> {
        self.d
            .abugida_scripts
            .get(lc_script_name)
            .map(|info| ((&info.rule_type).into(), info.default_vowel.as_str()))
    }

    pub fn num_prop(&self, s: &str) -> Option<&'static ArchivedNumProp> {
        self.d.num_props.get(s)
    }

    /// The actionable compatibility decomposition of a character.
    pub fn decomposition(&self, c: char) -> Option<(&'static str, &'static str)> {
        self.d
            .decompositions
            .get(&char_le::from_native(c))
            .map(|pair| (pair.0.as_str(), pair.1.as_str()))
    }

    pub fn percentage_markers(&self) -> impl Iterator<Item = &'static str> {
        self.d.percentage_markers.iter().map(|s| s.as_str())
    }

    pub fn fraction_connectors(&self) -> impl Iterator<Item = &'static str> {
        self.d.fraction_connectors.iter().map(|s| s.as_str())
    }

    pub fn plus_signs(&self) -> impl Iterator<Item = &'static str> {
        self.d.plus_signs.iter().map(|s| s.as_str())
    }

    pub fn minus_signs(&self) -> impl Iterator<Item = &'static str> {
        self.d.minus_signs.iter().map(|s| s.as_str())
    }

    /// Algorithmic romanization of a Hangul syllable by Jamo decomposition.
    pub fn hangul_romanization(&self, c: char) -> Option<String> {
        let cp = c as u32;
        if !(0xAC00..=0xD7A3).contains(&cp) {
            return None;
        }

        let code = cp - 0xAC00;
        let lead_index = (code / (28 * 21)) as usize;
        let vowel_index = ((code / 28) % 21) as usize;
        let tail_index = (code % 28) as usize;

        let rom = format!(
            "{}{}{}",
            HANGUL_LEADS[lead_index], HANGUL_VOWELS[vowel_index], HANGUL_TAILS[tail_index]
        );

        Some(rom.replace('-', ""))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The runtime uses `access_unchecked`; this test runs the full bytecheck
    /// validation over the embedded archive so that any corruption or layout
    /// mismatch is caught in CI.
    #[test]
    fn embedded_archive_validates() {
        let archived =
            rkyv::access::<ArchivedDictionaries, rkyv::rancor::Error>(DICT_BYTES).unwrap();
        assert!(!archived.rom_rules.is_empty());
        assert!(!archived.s_prefixes.is_empty());
        assert!(!archived.num_props.is_empty());
    }

    #[test]
    fn spot_check_lookups() {
        let dicts = Dicts::global();
        assert_eq!(dicts.chr_script_name('あ'), "Hiragana");
        assert!(
            dicts
                .rom_rules("あ")
                .iter()
                .any(|r| r.target() == Some("a"))
        );
        assert!(dicts.is_s_prefix("あ"));
        assert_eq!(dicts.hangul_romanization('한').as_deref(), Some("han"));
        assert!(dicts.num_prop("五").is_some());
    }
}
